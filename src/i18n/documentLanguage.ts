/**
 * 웹에서 **문서의 언어**(`<html lang>`)를 앱의 언어와 맞춘다 (W4 슬라이스 B).
 *
 * ── 왜 필요한가 ───────────────────────────────────────────────────────────────
 *
 * 화면 낭독기(시각장애인이 쓰는 읽어 주는 프로그램)와 브라우저는 **문서에 적힌 언어를 보고**
 * 그 글을 어느 발음으로 읽을지, 글자를 어느 글꼴로 그릴지, 줄을 어디서 끊을지 정한다. 이 앱의
 * 웹 판은 화면을 미리 한 번 찍어 두는 방식이라(`app/+html.tsx`) 그 자리에서는 사람이 무슨
 * 언어를 고를지 알 수 없고, 그래서 껍데기에는 기본값 `en` 이 박혀 있다. 한국어로 쓰는 사람의
 * 문서가 "영어"라고 말하고 있는 셈이며, 낭독기는 한국어 문장을 영어 발음으로 읽으려 한다.
 *
 * 고칠 수 있는 자리는 **설정이 바뀌는 순간뿐**이다. 그래서 앱이 켜질 때와 언어를 바꿀 때마다
 * 이 함수가 불려 문서의 언어를 실제 언어로 고쳐 쓴다(`app/_layout.tsx` 의 `Shell`).
 *
 * ── 이 한 줄이 화면 그림을 바꾼다 ──────────────────────────────────────────────
 *
 * 크로미움은 문서의 언어에 따라 글자 고르기와 줄 끊기를 바꾼다. 그래서 이 값이 `en` 에서
 * `ko` 로 옮겨 가면 **한국어 화면의 사진이 달라진다** — 슬라이스 A 가 껍데기의 값을 `ko` 로
 * 바꿔 보고 사진 스물여덟 장이 모두 달라지는 것을 실측했다(2026-09-18). 달라지는 것은 사진일
 * 뿐이고 화면이 잘못되는 것이 아니며, 오히려 **한국어로 읽히는 것이 맞는 상태**다.
 *
 * ── 앱(iOS·안드로이드)에서는 아무 일도 하지 않는다 ────────────────────────────
 *
 * 문서라는 것이 없기 때문이다. `document` 가 없으면 조용히 물러난다 — 플랫폼을 묻는 분기를
 * 따로 두지 않고 있는지만 보는 이유는, 같은 코드가 시험(jest, 문서 없음)에서도 그대로
 * 돌아야 하기 때문이다.
 */
import type { LanguageKey } from './index';

/**
 * 문서의 언어를 이 언어로 고쳐 쓴다.
 *
 * 언어 열쇠(`ko` · `en` · `it` …)를 그대로 쓴다. 이 일곱은 모두 ISO 639-1 의 두 글자
 * 언어 코드라 `lang` 속성이 그대로 받아들인다.
 */
export function syncDocumentLanguage(language: LanguageKey): void {
  if (typeof document === 'undefined') return;
  const root = document.documentElement;
  if (root && root.lang !== language) root.lang = language;
}

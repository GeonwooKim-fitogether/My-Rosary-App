/**
 * 알의 상태를 무엇으로 말하는가 — 빛의 값들 (2026-09-10, `decisions.md` 결정 10).
 *
 * ── 무엇이 바뀌었나 ──────────────────────────────────────────────────────────
 *
 * 그전까지 아직 안 바친 알은 **테만 두른 빈 동그라미**였고, 알을 바치면 그 동그라미가
 * 재질의 빛깔로 **채워졌다**. 공방장이 그 방식을 뒤집었다 — 실제 묵주는 기도한다고 알이
 * 채워지지 않는다. 그래서 이제 알 쉰아홉은 **언제나 같은 모습의 꽉 찬 알**이고, 어디까지
 * 바쳤는가는 **이미 바친 알이 환해지는 것**으로 말한다.
 *
 * ── 환해짐을 두 겹으로 만드는 이유 ────────────────────────────────────────────
 *
 * 밝은 한지 바탕(`#EDE7D8`)에서는 "빛난다"가 어렵다. 어두운 바탕에서는 알 둘레에 빛무리를
 * 두르면 곧바로 보이지만, 밝은 바탕에서는 그 빛이 바탕에 묻히기 때문이다. 그래서 빛을 두
 * 겹으로 나눠 얹었고, 두 겹이 함께 있어야 낮에도 경계가 선다.
 *
 * 1. **알 둘레의 빛무리**(`BEAD_GLOW`). 알보다 넓은 원 하나를 알 밑에 깔고 바깥으로
 *    사라지게 그린다. 알과 알의 사이가 좁아 이웃한 빛무리끼리 겹치므로, 바친 구간이
 *    낱낱의 점이 아니라 **이어진 빛의 띠**로 읽힌다 — 이것이 낮에 경계를 세우는 힘이다.
 * 2. **알 자신의 밝아짐**(`BEAD_SHADING`). 알에 얹는 빛을 더 세게, 그늘을 더 옅게 해서
 *    알 자체가 환해진다. 채우기를 바꾸지 않으므로 두 알의 **색은 여전히 같다** — 달라지는
 *    것은 그 색이 얼마나 빛을 받고 있는가뿐이다.
 */

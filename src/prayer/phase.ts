/**
 * 지금 알의 상태(phase) — 기도 화면 가운데 알이 "지금 무슨 일이 벌어지고 있나"를 말하는 값
 * (FR-15 · 06-screen-spec 화면 B 요소 표 · 06-design-system §4-2).
 *
 * 묵주 그림은 오래도록 진행(바친 알 · 지금 알 · 안 바친 알)만 말하고 지금 이 순간의 일은
 * 말하지 않았다. 앱이 읽는 중인지, 내가 받을 차례인지, 멈춰 있는지가 그림에 드러나지
 * 않았다는 뜻이다. 이 파일은 그 다섯 상태의 이름을 한 곳에 둔다. 값을 만드는 곳은
 * 진행기(`runner.ts`)와 세션 갈고리(`usePrayerSession.ts`)이고, 값을 그리는 곳은 묵주 그림
 * (`Rosary.tsx`)이다. 셋이 같은 이름을 쓰게 하려고 어느 쪽에도 속하지 않는 파일로 뺐다.
 *
 * | 값 | 뜻 | 화면 명세가 정한 표현 |
 * |---|---|---|
 * | `reading` | 앱이 절을 읽는 중 | 알의 테두리가 읽는 절의 길이에 맞춰 차오른다 |
 * | `response` | 내가 받을 차례 (받는 사이) | 4초 주기 호흡 |
 * | `silent` | 읽지 않기 방식으로 진행 중 — 소리 없이 사이만 흐른다 | 알을 넘길 때의 진동에 맞춰 한 번 반짝 |
 * | `decade` | 단이 막 바뀌었다 | 확장 맥동 한 번 |
 * | `paused` | 멈춤 | 호흡이 멎고 흐려진다 |
 *
 * 앞의 넷은 진행기가 알고 있는 사실이라 진행기가 내보내고(`RunnerPhase`), 마지막 `paused`
 * 는 진행기의 `isRunning()` 이 거짓이라는 뜻이라 세션 갈고리가 붙인다.
 */

/** 진행기가 내보내는 상태 넷. */
export type RunnerPhase = 'reading' | 'response' | 'silent' | 'decade';

/** 화면이 받는 상태 다섯. */
export type PrayerPhase = RunnerPhase | 'paused';

/**
 * 단 전환의 확장 맥동이 걸리는 시간이자, 세션 갈고리가 `decade` 상태를 붙들어 두는 시간.
 *
 * 진행기는 단이 바뀌는 순간 `decade` 를 알리고 곧바로 다음 단계의 `reading` 을 알린다 —
 * 둘 사이에 기다림이 없다. 그대로 화면에 넘기면 두 값이 한 번의 그리기로 합쳐져 `decade`
 * 는 그려지지 못한다. 그래서 갈고리가 이 시간만큼 `decade` 를 붙들고, 그 사이에 온 다음
 * 상태는 시간이 끝난 뒤에 넘긴다.
 *
 * 값은 06-design-system §6 의 **화면 전환 500ms** 에서 가져왔다. 시안(v5)에는 단 전환의
 * 움직임이 따로 없어, 모션 표에서 "한 상태에서 다른 상태로 넘어가는 움직임"에 해당하는
 * 가장 가까운 값을 골랐다.
 */
export const DECADE_PULSE_MS = 500;

/**
 * 화면 낭독기와 시험이 읽는 상태 이름. 색과 움직임을 볼 수 없는 사용자에게도 다섯 상태가
 * 전해져야 한다 (06-design-system §7 — 색만으로 상태를 알리지 않는다).
 */
export const PHASE_LABEL: Readonly<Record<PrayerPhase, string>> = {
  reading: '지금 알: 앱이 읽는 중',
  response: '지금 알: 내가 받을 차례',
  silent: '지금 알: 소리 없이 진행 중',
  decade: '지금 알: 단이 바뀌었습니다',
  paused: '지금 알: 멈춤',
};

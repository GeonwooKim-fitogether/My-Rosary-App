/**
 * 기도를 마치거나 멈추고 앱의 첫 화면으로 돌아가는 한 곳.
 *
 * **왜 `replace` 가 아니라 `back` 인가.** 로그인 화면에서 기도 화면으로 들어갈 때
 * 기도 화면이 로그인 화면 위에 쌓인다. 여기서 `replace('/')` 를 부르면 맨 위의 기도
 * 화면만 로그인 화면으로 바뀌고 **밑에 깔린 로그인 화면은 그대로 남아** 같은 화면이
 * 둘이 된다. 이 결함은 눈으로는 보이지 않고(둘이 똑같이 생겼다) 화면 검사에서 잡혔다.
 * 그래서 쌓인 것을 덮지 않고 걷어 낸다.
 *
 * 되돌아갈 자리가 없을 때(주소로 기도 화면을 바로 열었을 때)만 첫 화면으로 갈아 끼운다.
 *
 * **M2 에서 홈 화면이 서면 이 함수가 가리키는 곳이 홈이 된다.** 지금은 앱의 첫 화면이
 * 로그인 하나뿐이라 그리로 간다.
 */
import { router } from 'expo-router';

export function leaveToHome(): void {
  if (router.canGoBack()) {
    router.back();
    return;
  }
  router.replace('/');
}

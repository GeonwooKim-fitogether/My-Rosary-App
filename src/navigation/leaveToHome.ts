/**
 * 기도를 마치거나 멈추고 여정 목록(홈)으로 돌아가는 한 곳.
 *
 * **왜 `replace` 가 아닌가.** 화면은 쌓인다 — 로그인 위에 홈, 홈 위에 기도. 여기서
 * `replace('/home')` 을 부르면 맨 위의 기도 화면만 홈으로 바뀌고 **밑에 깔린 홈은 그대로
 * 남아** 같은 화면이 둘이 된다. 이 결함은 눈으로는 보이지 않고(둘이 똑같이 생겼다) 화면
 * 검사에서만 잡히며, M1 에서 로그인 화면으로 한 번, M2 에서 홈 화면으로 한 번 실제로
 * 걸렸다. 그래서 쌓인 것을 덮지 않고 **걷어 낸다.**
 *
 * 그래서 쌓인 것을 **걷어 낸다**(`back`). 되돌아갈 자리가 없을 때(주소로 기도 화면을 바로
 * 열었을 때)만 홈으로 갈아 끼운다.
 *
 * `dismissTo('/home')` 도 시험해 보았는데, 이 판(expo-router 57)의 웹에서는 스택을 되감지
 * 않고 홈을 **한 장 더 얹었다** — 화면에 홈이 둘이 되고 하나는 숨어 있었다. 실측으로 확인한
 * 사실이라 적어 둔다.
 */
import { router } from 'expo-router';

export function leaveToHome(): void {
  if (router.canGoBack()) {
    router.back();
    return;
  }
  router.replace('/home');
}
